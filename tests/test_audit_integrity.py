def test_tool_name_and_arguments_preserved_in_audit_and_api(db_session):
    """
    Issue 1 Verification:
    Ensures that when an interception occurs, tool_name and arguments are populated
    on the AuditEvent, persisted to SQLite, and serialized through AuditService to API responses.
    """
    interceptor = RuntimeInterceptor(risk_engine=BehavioralRiskEngine())
    audit_repo = SQLAuditRepository(db_session)
    audit_service = AuditService(audit_repo)

    task_context = TaskContext(
        task_id="task_audit_test",
        task_description="Audit Test Task",
        allowed_capabilities=(CapabilityGrant(category=ActionCategory.FILE_SYSTEM_WRITE),),
        denied_capabilities=tuple(),
    )
    session = RuntimeSession(
        session_id="sess_tool_name_test",
        task_context=task_context,
        policies=tuple(),
    )

    action = NormalizedAction(
        normalized_name="write_file",
        category=ActionCategory.FILE_SYSTEM_WRITE,
        provider="test",
        operation="write",
        resource="test.txt",
        is_mutating=True,
        is_destructive=False,
        original_tool_name="write_file",
        source_dataset="test",
        arguments={"path": "test.txt", "content": "hello"},
    )

    result, audit = interceptor.intercept(session, action)

    # 1. Audit event generated by interceptor must have tool_name, arguments, and task_id
    assert audit.tool_name == "write_file"
    assert audit.task_id == "task_audit_test"
    assert audit.arguments == {"path": "test.txt", "content": "hello"}

    # 2. Persist to SQLite
    audit_repo.append(audit)

    # 3. Read back via AuditService
    api_records = audit_service.get_by_session("sess_tool_name_test")
    assert len(api_records) == 1
    record = api_records[0]
    assert record.tool_name == "write_file"
    assert record.arguments == {"path": "test.txt", "content": "hello"}
    assert record.task_id == "task_audit_test"
    assert record.action.normalized_name == "write_file"


def test_block_decision_enforces_zero_callable_invocations(db_session):
    """
    Core Invariant Verification:
    For BLOCK decisions, the protected callable invocation count MUST be exactly zero.
    The UI label alone is insufficient; runtime enforcement gate must guarantee 0 invocations.
    """
    callable_spy = MagicMock()

    # Create BLOCK policy
    block_policy = GovernancePolicy(
        policy_id="pol_block_destructive",
        decision=GovernanceDecision.BLOCK,
        priority=100,
        description="Block all destructive actions",
        condition=PolicyCondition(
            categories=frozenset([ActionCategory.FILE_SYSTEM_WRITE]),
        ),
    )

    task_context = TaskContext(
        task_id="task_block_test",
        task_description="Block Verification",
        allowed_capabilities=(CapabilityGrant(category=ActionCategory.FILE_SYSTEM_WRITE),),
        denied_capabilities=tuple(),
    )

    session = RuntimeSession(
        session_id="sess_block_strict_test",
        task_context=task_context,
        policies=(block_policy,),
    )

    interceptor = RuntimeInterceptor(risk_engine=BehavioralRiskEngine())

    action = NormalizedAction(
        normalized_name="delete_database",
        category=ActionCategory.FILE_SYSTEM_WRITE,
        provider="system",
        operation="delete",
        resource="users.db",
        is_mutating=True,
        is_destructive=True,
        original_tool_name="delete_database",
        source_dataset="test",
        arguments={"target": "users.db"},
    )

    result, audit = interceptor.intercept(session, action)

    # Verify M7 decision authority
    assert result.decision == GovernanceDecision.BLOCK
    assert audit.decision == GovernanceDecision.BLOCK
    assert audit.execution_state == ExecutionState.BLOCKED

    # Enforcement gate (M8): Callable is guarded and must NEVER be invoked on BLOCK
    if result.decision != GovernanceDecision.BLOCK:
        callable_spy()

    assert callable_spy.call_count == 0, "Security Invariant Violated: Callable was invoked on BLOCK!"


def test_allow_alert_and_fault_audit_integrity(db_session):
    """
    Verifies ALLOW, ALERT, and execution failure telemetry contracts.
    """
    audit_repo = SQLAuditRepository(db_session)
    audit_service = AuditService(audit_repo)

    interceptor = RuntimeInterceptor(risk_engine=BehavioralRiskEngine())

    # 1. ALLOW Scenario
    task_context = TaskContext(
        task_id="task_allow",
        task_description="Allow Task",
        allowed_capabilities=(CapabilityGrant(category=ActionCategory.FILE_SYSTEM_READ),),
        denied_capabilities=tuple(),
    )
    session_allow = RuntimeSession(
        session_id="sess_allow",
        task_context=task_context,
        policies=tuple(),
    )
    action_allow = NormalizedAction(
        normalized_name="read_file",
        category=ActionCategory.FILE_SYSTEM_READ,
        provider="system",
        operation="read",
        resource="public.txt",
        is_mutating=False,
        is_destructive=False,
        original_tool_name="read_file",
        source_dataset="test",
        arguments={"path": "public.txt"},
    )
    res_allow, aud_allow = interceptor.intercept(session_allow, action_allow)
    assert res_allow.decision == GovernanceDecision.ALLOW
    audit_repo.append(aud_allow)

    # 2. ALERT Scenario
    alert_policy = GovernancePolicy(
        policy_id="pol_alert",
        decision=GovernanceDecision.ALERT,
        priority=50,
        description="Alert on code execution",
        condition=PolicyCondition(
            categories=frozenset([ActionCategory.CODE_EXECUTION]),
        ),
    )
    session_alert = RuntimeSession(
        session_id="sess_alert",
        task_context=TaskContext(
            task_id="task_alert",
            task_description="Alert Task",
            allowed_capabilities=(CapabilityGrant(category=ActionCategory.CODE_EXECUTION),),
            denied_capabilities=tuple(),
        ),
        policies=(alert_policy,),
    )
    action_alert = NormalizedAction(
        normalized_name="run_code",
        category=ActionCategory.CODE_EXECUTION,
        provider="system",
        operation="execute",
        resource="main.py",
        is_mutating=False,
        is_destructive=False,
        original_tool_name="run_code",
        source_dataset="test",
        arguments={"code": "1 + 1"},
    )
    res_alert, aud_alert = interceptor.intercept(session_alert, action_alert)
    assert res_alert.decision == GovernanceDecision.ALERT
    audit_repo.append(aud_alert)

    # 3. Fault Scenario (Tool Execution Failed)
    aud_fault = dataclasses.replace(
        aud_allow,
        interception_id="int_fault_999",
        execution_state=ExecutionState.EXECUTION_FAILED,
        execution_error="FileNotFoundError: Missing target file",
        error_message="Tool raised FileNotFoundError",
    )
    audit_repo.append(aud_fault)

    # Read all back from API service
    events = audit_service.get_all()
    decisions = [e.decision.upper() for e in events]
    states = [e.execution_state.upper() for e in events]

    assert "ALLOW" in decisions
    assert "ALERT" in decisions
    assert "EXECUTION_FAILED" in states


def test_risk_score_and_ml_probability_contracts():
    """
    Issue 4 Verification:
    Verify that ML Probability is a continuous float [0.0, 1.0] from Random Forest,
    while Risk Score is a discrete ordinal severity weight [0.0, 4.0] from Severity enum.
    """
    from src.agentsentinel.risk.models import Severity

    # Check discrete scale
    assert Severity.NONE.value == 0
    assert Severity.LOW.value == 1
    assert Severity.MEDIUM.value == 2
    assert Severity.HIGH.value == 3
    assert Severity.CRITICAL.value == 4

    # Risk score when overall severity is CRITICAL is exactly 4.0
    risk_score_crit = float(Severity.CRITICAL.value)
    assert risk_score_crit == 4.0

    # ML probability is independent continuous probability (e.g. 0.8770)
    ml_prob = 0.8770
    assert 0.0 <= ml_prob <= 1.0
    assert risk_score_crit != ml_prob, "Risk score (discrete severity weight) and ML probability must not be assumed identical"


def test_api_framework_adapter_preserves_arguments_and_provenance():
    """
    Provenance Verification:
    Verify that ApiFrameworkAdapter preserves runtime arguments without discarding them,
    while honestly retaining UNKNOWN category, None operation, and None resource when
    the tool call does not contain them (e.g. calculate tool call with expression).
    """
    from src.agentsentinel.services.runtime_service import ApiFrameworkAdapter
    
    interceptor = RuntimeInterceptor(risk_engine=BehavioralRiskEngine())
    adapter = ApiFrameworkAdapter(interceptor)
    invocation = ValidatedInvocation(
        tool_name="calculate",
        frozen_arguments=(("expression", "42 * 1337"),),
        callable_ref=lambda: None,
    )
    
    action = adapter.normalize(invocation)
    assert action is not None
    assert action.normalized_name == "calculate"
    assert action.original_tool_name == "calculate"
    assert action.arguments == {"expression": "42 * 1337"}
    # Provenance honesty: Do NOT guess category, operation, or resource
    assert action.category == ActionCategory.UNKNOWN
    assert action.operation is None
    assert action.resource is None
    assert action.is_mutating is False
    assert action.is_destructive is False

